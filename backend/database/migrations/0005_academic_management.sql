-- CourseHubs Phase 1: academic structure and course management.
-- New schema is additive; existing accounts, sessions, courses and offerings are preserved.

CREATE TABLE IF NOT EXISTS faculties (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    code VARCHAR(24) NOT NULL,
    description TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_faculties_code_ci ON faculties (LOWER(code));
CREATE UNIQUE INDEX IF NOT EXISTS uq_faculties_name_ci ON faculties (LOWER(name));
CREATE INDEX IF NOT EXISTS idx_faculties_active_name ON faculties (is_active, name);

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT NOT NULL REFERENCES faculties(id),
    name VARCHAR(160) NOT NULL,
    code VARCHAR(24) NOT NULL,
    description TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_departments_faculty_code_ci ON departments (faculty_id, LOWER(code));
CREATE UNIQUE INDEX IF NOT EXISTS uq_departments_faculty_name_ci ON departments (faculty_id, LOWER(name));
CREATE INDEX IF NOT EXISTS idx_departments_faculty_active ON departments (faculty_id, is_active, name);

CREATE TABLE IF NOT EXISTS programmes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id BIGINT NOT NULL REFERENCES departments(id),
    name VARCHAR(160) NOT NULL,
    code VARCHAR(30) NOT NULL,
    award VARCHAR(80) NOT NULL DEFAULT 'Bachelor of Science',
    duration_years SMALLINT NOT NULL DEFAULT 4 CHECK (duration_years BETWEEN 1 AND 10),
    description TEXT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by BIGINT NOT NULL REFERENCES users(id),
    updated_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_programmes_department_code_ci ON programmes (department_id, LOWER(code));
CREATE UNIQUE INDEX IF NOT EXISTS uq_programmes_department_name_ci ON programmes (department_id, LOWER(name));
CREATE INDEX IF NOT EXISTS idx_programmes_department_active ON programmes (department_id, is_active, name);

CREATE TABLE IF NOT EXISTS academic_levels (
    level SMALLINT PRIMARY KEY CHECK (level IN (100, 200, 300, 400, 500, 600)),
    label VARCHAR(20) NOT NULL UNIQUE,
    sort_order SMALLINT NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO academic_levels (level, label, sort_order) VALUES
    (100, '100 Level', 1),
    (200, '200 Level', 2),
    (300, '300 Level', 3),
    (400, '400 Level', 4),
    (500, '500 Level', 5),
    (600, '600 Level', 6)
ON CONFLICT (level) DO NOTHING;

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS department_id BIGINT NULL REFERENCES departments(id),
    ADD COLUMN IF NOT EXISTS programme_id BIGINT NULL REFERENCES programmes(id);

ALTER TABLE users
    ADD CONSTRAINT chk_users_programme_requires_department
    CHECK (programme_id IS NULL OR department_id IS NOT NULL);

ALTER TABLE courses
    ADD COLUMN IF NOT EXISTS department_id BIGINT NULL REFERENCES departments(id),
    ADD COLUMN IF NOT EXISTS description TEXT NULL,
    ADD COLUMN IF NOT EXISTS is_active BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN IF NOT EXISTS is_university_wide BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ADD COLUMN IF NOT EXISTS created_by BIGINT NULL REFERENCES users(id),
    ADD COLUMN IF NOT EXISTS updated_by BIGINT NULL REFERENCES users(id);

ALTER TABLE courses
    ADD CONSTRAINT chk_courses_university_wide_no_department
    CHECK (is_university_wide IS FALSE OR department_id IS NULL);

CREATE INDEX IF NOT EXISTS idx_courses_department_active ON courses (department_id, is_active) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_courses_code_ci_active ON courses (LOWER(current_code)) WHERE deleted_at IS NULL;

ALTER TABLE course_offerings
    ADD COLUMN IF NOT EXISTS programme_id BIGINT NULL REFERENCES programmes(id);

ALTER TABLE course_offerings
    DROP CONSTRAINT IF EXISTS uq_offering_identity;

CREATE UNIQUE INDEX IF NOT EXISTS uq_course_offerings_identity
    ON course_offerings (course_id, COALESCE(programme_id, 0), level, academic_session_id, semester)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_users_academic_affiliation ON users (department_id, programme_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_course_offering_lecturers_offering ON course_offering_lecturers (course_offering_id);

CREATE INDEX IF NOT EXISTS idx_course_offerings_catalog
    ON course_offerings (academic_session_id, programme_id, level, semester)
    WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_academic_sessions_single_current
    ON academic_sessions ((is_current))
    WHERE is_current IS TRUE;

CREATE TABLE IF NOT EXISTS coursehubs_bootstrap_state (
    bootstrap_key VARCHAR(80) PRIMARY KEY,
    completed_at TIMESTAMPTZ NULL,
    completed_user_id BIGINT NULL REFERENCES users(id)
);

INSERT INTO coursehubs_bootstrap_state (bootstrap_key)
VALUES ('initial_super_admin')
ON CONFLICT (bootstrap_key) DO NOTHING;

