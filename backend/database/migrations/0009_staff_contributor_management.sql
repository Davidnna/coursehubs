-- CourseHubs Phase 4: academic staff and contributor assignment management.
-- Additive migration: preserves existing staff accounts and assignment history.

ALTER TABLE level_advisers
    ADD COLUMN IF NOT EXISTS programme_id BIGINT NULL REFERENCES programmes(id);

CREATE INDEX IF NOT EXISTS idx_level_advisers_programme_cohort
    ON level_advisers (programme_id, current_level, academic_session_id, status);

CREATE UNIQUE INDEX IF NOT EXISTS uq_level_advisers_active_staff_cohort
    ON level_advisers (user_id, programme_id, current_level, expected_graduation_session_id)
    WHERE status = 'active' AND programme_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_course_offering_linked_lecturer
    ON course_offering_lecturers (course_offering_id, lecturer_user_id)
    WHERE lecturer_user_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_level_reps_active_user
    ON level_reps (user_id, status);

CREATE TABLE IF NOT EXISTS academic_staff_assignment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_type VARCHAR(24) NOT NULL
        CHECK (assignment_type IN ('lecturer', 'course_rep', 'course_adviser')),
    assignment_id BIGINT NOT NULL,
    assigned_user_id BIGINT NOT NULL REFERENCES users(id),
    action VARCHAR(12) NOT NULL CHECK (action IN ('assigned', 'revoked')),
    changed_by BIGINT NOT NULL REFERENCES users(id),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_staff_assignment_history_user
    ON academic_staff_assignment_history (assigned_user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_staff_assignment_history_assignment
    ON academic_staff_assignment_history (assignment_type, assignment_id, created_at DESC);
