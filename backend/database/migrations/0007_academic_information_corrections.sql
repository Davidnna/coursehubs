-- CourseHubs: verified student academic information corrections.
-- Additive migration; existing account and level-correction history is preserved.

CREATE TABLE IF NOT EXISTS academic_information_correction_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    current_department_id BIGINT NULL REFERENCES departments(id),
    current_programme_id BIGINT NULL REFERENCES programmes(id),
    current_level SMALLINT NULL,
    requested_department_id BIGINT NULL REFERENCES departments(id),
    requested_department_name VARCHAR(160) NULL,
    requested_programme_id BIGINT NULL REFERENCES programmes(id),
    requested_programme_name VARCHAR(160) NULL,
    requested_level SMALLINT NOT NULL CHECK (requested_level IN (100, 200, 300, 400, 500, 600)),
    reason TEXT NOT NULL,
    status VARCHAR(8) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    decision_note TEXT NULL,
    approved_department_id BIGINT NULL REFERENCES departments(id),
    approved_programme_id BIGINT NULL REFERENCES programmes(id),
    approved_level SMALLINT NULL CHECK (approved_level IS NULL OR approved_level IN (100, 200, 300, 400, 500, 600)),
    reviewed_by BIGINT NULL REFERENCES users(id),
    reviewed_at TIMESTAMPTZ NULL,
    legacy_level_request_id BIGINT NULL UNIQUE REFERENCES level_correction_requests(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_academic_correction_department_choice
        CHECK (requested_department_id IS NULL OR requested_department_name IS NULL),
    CONSTRAINT chk_academic_correction_programme_choice
        CHECK (requested_programme_id IS NULL OR requested_programme_name IS NULL),
    CONSTRAINT chk_academic_correction_approved_values
        CHECK (
            (approved_department_id IS NULL AND approved_programme_id IS NULL AND approved_level IS NULL)
            OR
            (approved_department_id IS NOT NULL AND approved_programme_id IS NOT NULL AND approved_level IS NOT NULL)
        ),
    CONSTRAINT chk_academic_correction_reason
        CHECK (length(btrim(reason)) BETWEEN 10 AND 1500)
);

CREATE INDEX IF NOT EXISTS idx_academic_correction_pending_user
    ON academic_information_correction_requests (user_id, created_at DESC)
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS idx_academic_correction_status_created
    ON academic_information_correction_requests (status, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_academic_correction_user_created
    ON academic_information_correction_requests (user_id, created_at DESC);

-- Migrate any historical level-only requests into the unified correction queue.
-- The old table remains intact for audit compatibility.
INSERT INTO academic_information_correction_requests (
    user_id, current_department_id, current_programme_id, current_level,
    requested_department_id, requested_programme_id, requested_level,
    reason, status, decision_note, reviewed_by, reviewed_at,
    legacy_level_request_id, created_at
)
SELECT
    legacy_req.user_id, u.department_id, u.programme_id, u.level,
    u.department_id, u.programme_id, legacy_req.requested_level,
    CASE
        WHEN length(btrim(legacy_req.reason)) < 10 THEN left('Legacy level correction request: ' || btrim(legacy_req.reason), 1500)
        ELSE left(legacy_req.reason, 1500)
    END,
    legacy_req.status, legacy_req.decision_note, legacy_req.reviewed_by, legacy_req.reviewed_at,
    legacy_req.id, legacy_req.created_at
FROM level_correction_requests legacy_req
JOIN users u ON u.id = legacy_req.user_id AND u.account_type = 'student'
WHERE NOT EXISTS (
    SELECT 1
    FROM academic_information_correction_requests existing
    WHERE existing.legacy_level_request_id = legacy_req.id
);
