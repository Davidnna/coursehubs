-- =====================================================================
-- 10. EMAIL QUOTA TRACKING
-- =====================================================================

-- Counts emails sent against a given calendar date (WAT), so a batch
-- send can check remaining quota before firing. If a batch would
-- exceed what's left for today, the whole batch's email is skipped
-- (not sent to a partial subset) and in-app notification stands alone
-- for that batch.
CREATE TABLE email_send_log (
    send_date   DATE PRIMARY KEY,
    sent_count  INTEGER NOT NULL DEFAULT 0
);

-- Soft-delete-aware uniqueness: only non-deleted records reserve identifiers.
CREATE UNIQUE INDEX uq_users_email_active ON users (email) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_users_regno_active ON users (reg_no) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_users_staffno_active ON users (staff_no) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_courses_code_active ON courses (current_code) WHERE deleted_at IS NULL;

-- Additional indexes and full-text search.
CREATE INDEX idx_codehist_oldcode ON course_code_history (old_code);
CREATE INDEX ftx_uploads_search ON uploads USING GIN (search_vector);
CREATE INDEX idx_flags_target ON flags (flaggable_type, flaggable_id);

-- Keep updated_at current on updates through PostgreSQL triggers.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON users
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_level_reps_updated_at
BEFORE UPDATE ON level_reps
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_level_advisers_updated_at
BEFORE UPDATE ON level_advisers
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_course_offerings_updated_at
BEFORE UPDATE ON course_offerings
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TRIGGER trg_admin_settings_updated_at
BEFORE UPDATE ON admin_settings
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

