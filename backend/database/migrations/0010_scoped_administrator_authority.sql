-- Restore hierarchical administrator scopes without changing academic records.

CREATE TABLE IF NOT EXISTS administrator_scopes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    scope_type VARCHAR(16) NOT NULL CHECK (scope_type IN ('institution', 'faculty', 'department')),
    scope_id BIGINT NULL,
    role VARCHAR(12) NOT NULL CHECK (role IN ('admin', 'super_admin')),
    assigned_by BIGINT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_administrator_scope_target CHECK (
        (scope_type = 'institution' AND scope_id IS NULL) OR
        (scope_type IN ('faculty', 'department') AND scope_id IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_administrator_scopes_assignment
    ON administrator_scopes (user_id, scope_type, COALESCE(scope_id, 0));
CREATE INDEX IF NOT EXISTS idx_administrator_scopes_scope
    ON administrator_scopes (scope_type, scope_id, role);
CREATE INDEX IF NOT EXISTS idx_administrator_scopes_user
    ON administrator_scopes (user_id, scope_type);

-- Existing institution administrators retain their institution-wide authority.
INSERT INTO administrator_scopes (user_id, scope_type, scope_id, role, assigned_by)
SELECT id, 'institution', NULL,
       CASE WHEN is_super_admin IS TRUE THEN 'super_admin' ELSE 'admin' END,
       NULL
FROM users
WHERE is_admin IS TRUE AND deleted_at IS NULL
ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS administrator_scope_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    scope_type VARCHAR(16) NOT NULL CHECK (scope_type IN ('institution', 'faculty', 'department')),
    scope_id BIGINT NULL,
    role VARCHAR(12) NOT NULL CHECK (role IN ('admin', 'super_admin')),
    action VARCHAR(12) NOT NULL CHECK (action IN ('assigned', 'revoked')),
    changed_by BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_administrator_scope_history_user
    ON administrator_scope_history (user_id, created_at DESC);

CREATE OR REPLACE FUNCTION prevent_administrator_scope_history_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Administrator scope history is immutable';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_administrator_scope_history_immutable ON administrator_scope_history;
CREATE TRIGGER trg_administrator_scope_history_immutable
BEFORE UPDATE OR DELETE ON administrator_scope_history
FOR EACH ROW EXECUTE FUNCTION prevent_administrator_scope_history_mutation();
